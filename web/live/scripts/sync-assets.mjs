// Builds the engine and the authoring adapter, then copies them with the shared
// worklet modules into web/live so Vite's dev server and production build serve
// the current engine. Any missing file fails the run.
//
// Run by `npm run sync:assets`, automatically before `dev` and `build`.

import { mkdirSync, copyFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const liveDir = resolve(here, "..");
const webDir = resolve(liveDir, "..");
const repoDir = resolve(webDir, "..");
const publicDir = resolve(liveDir, "public");
const generatedDir = resolve(liveDir, "src/generated");
const releaseBuildDir = (target) => resolve(repoDir, "_build", target, "release/build");

function moonBuild(pkg, target) {
  execFileSync("moon", ["build", pkg, "--target", target, "--release"], {
    cwd: repoDir,
    env: { ...process.env, NEW_MOON_MOD: "0" },
    stdio: "inherit",
  });
}

function copy(source, destination) {
  copyFileSync(source, destination);
  console.log(`[sync-assets] ${destination}`);
}

moonBuild("browser", "wasm-gc");
moonBuild("browser_authoring", "js");

mkdirSync(generatedDir, { recursive: true });
const authoringSource = resolve(releaseBuildDir("js"), "browser_authoring/browser_authoring.js");

// The editor needs the engine's nesting rules before authoring loads lazily,
// so they are read from the engine here, parsed once, and written as a module.
const { control_nesting: controlNesting } = await import(pathToFileURL(authoringSource).href);
const nesting = JSON.parse(controlNesting());
if (typeof nesting !== "object" || nesting === null || Array.isArray(nesting)) {
  throw new Error("[sync-assets] control_nesting() did not return an object");
}
for (const [control, rule] of Object.entries(nesting)) {
  if (rule !== "multiply" && rule !== "override") {
    throw new Error(`[sync-assets] invalid nesting rule for ${control}: ${rule}`);
  }
}
writeFileSync(
  resolve(generatedDir, "control-nesting.js"),
  `// Generated by scripts/sync-assets.mjs from browser_authoring.control_nesting().\n` +
    `export const CONTROL_NESTING = Object.freeze(${JSON.stringify(nesting)});\n`,
);
console.log("[sync-assets] control-nesting.js");
mkdirSync(publicDir, { recursive: true });
copy(authoringSource, resolve(generatedDir, "authoring.js"));
copy(resolve(releaseBuildDir("wasm-gc"), "browser/browser.wasm"), resolve(publicDir, "moonbit_dsp.wasm"));
for (const worklet of ["playback-controller.js", "playback-onsets.js", "sample-loader.js", "scheduler-processor.js"]) {
  copy(resolve(webDir, worklet), resolve(publicDir, worklet));
}
